// Command ml-eval evaluates a lightweight anomaly detector
// against the proxy's existing threshold rules, offline,
// over structured JSON logs (Batch 3, item 4).
//
// It answers one question: does a multivariate detector
// over request rate, fingerprint/UA/path diversity, risk
// score, and fingerprint concentration beat a per-IP
// request-count threshold at telling attack windows from
// normal windows? The evaluation is deliberately boring:
//
//   - Samples are (IP, 10-second window) aggregates of log
//     entries. Labels come from a labels file of attack
//     intervals: a window overlapping an attack interval is
//     an attack sample.
//   - The split is time-based (first 70% train, rest test),
//     so the test set is always the future relative to the
//     train set. Thresholds are tuned on train only.
//   - The baseline is the rule the proxy already enforces
//     in spirit: flag the sample when its request count
//     exceeds a threshold tuned on train.
//   - The candidate is a weighted z-score detector:
//     features are standardized on TRAIN NORMAL samples
//     only (classic anomaly detection: normal is the
//     reference), each feature contributes in its anomaly
//     direction (high count, low diversity, high risk,
//     high fingerprint concentration), and the threshold is
//     tuned on train for max F1.
//
// The program prints confusion counts, precision, recall,
// and F1 for both detectors on the held-out test split,
// and exits 0 when the evaluation ran (regardless of which
// detector won — the verdict is data, not a build gate).
//
// Honesty limits, stated here and in docs/ml-evaluation.md:
// the data is synthetic traffic generated by the Batch 3
// smoke harness (real proxy, real logs, scripted clients),
// every request was sent without a stored cookie so each
// produced one challenge log entry, and the sample counts
// are small. Numbers from this evaluation describe the
// synthetic setup only. The ship rule was fixed before the
// numbers were seen: ship a log-only detector only if the
// candidate beats the baseline F1 on the test split by at
// least 0.10 with test precision at least 0.70.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

// logEntry is the subset of logging.Entry fields the
// evaluation uses.
type logEntry struct {
	Timestamp   time.Time `json:"ts"`
	Event       string    `json:"event"`
	IP          string    `json:"ip"`
	Action      string    `json:"action"`
	Fingerprint string    `json:"fingerprint"`
	JA4         string    `json:"ja4"`
	RiskScore   int       `json:"risk_score"`
	Path        string    `json:"path"`
	UserAgent   string    `json:"user_agent"`
}

// interval is one labeled time range: attack=true means
// every overlapping window is an attack sample.
type interval struct {
	start, end time.Time
	attack     bool
}

// sample is one (IP, 10s window) aggregate.
type sample struct {
	window   int64 // unix seconds, 10s-aligned
	ip       string
	label    bool // true = attack
	features [nFeatures]float64
}

const (
	fCount = iota
	fDistinctPaths
	fDistinctUAs
	fDistinctFPs
	fMeanRisk
	fChallengeShare
	fFPShare
	nFeatures
)

var featureNames = [nFeatures]string{
	"count", "distinct_paths", "distinct_uas", "distinct_fps",
	"mean_risk", "challenge_share", "fp_share",
}

// anomalyDir is the anomaly direction per feature: +1 means
// high values are suspicious, -1 means low values are.
var anomalyDir = [nFeatures]float64{+1, -1, -1, -1, +1, +1, +1}

func main() {
	logPath := flag.String("log", "", "JSON-lines log file (required)")
	labelsPath := flag.String("labels", "", "labels file: startUnix,endUnix,attack(0|1) per line (required)")
	trainFrac := flag.Float64("train-frac", 0.7, "fraction of samples (by time) used for training")
	flag.Parse()
	if *logPath == "" || *labelsPath == "" {
		fmt.Fprintln(os.Stderr, "usage: ml-eval -log <jsonl> -labels <file> [-train-frac 0.7]")
		os.Exit(2)
	}
	intervals, err := loadLabels(*labelsPath)
	if err != nil {
		fatal(err)
	}
	entries, err := loadLog(*logPath)
	if err != nil {
		fatal(err)
	}
	samples := aggregate(entries, intervals)
	if len(samples) == 0 {
		fatal(fmt.Errorf("no samples: log has no entries with an IP inside a labeled interval"))
	}
	sort.Slice(samples, func(i, j int) bool {
		if samples[i].window != samples[j].window {
			return samples[i].window < samples[j].window
		}
		return samples[i].ip < samples[j].ip
	})
	cut := int(float64(len(samples)) * *trainFrac)
	if cut < 1 {
		cut = 1
	}
	if cut >= len(samples) {
		cut = len(samples) - 1
	}
	train, test := samples[:cut], samples[cut:]
	fmt.Printf("samples: total=%d train=%d test=%d\n", len(samples), len(train), len(test))
	fmt.Printf("train: attack=%d normal=%d; test: attack=%d normal=%d\n",
		countLabel(train, true), countLabel(train, false),
		countLabel(test, true), countLabel(test, false))

	// Baseline: count threshold tuned on train.
	bestT, bestF1 := tuneThreshold(train, func(s sample) float64 { return s.features[fCount] })
	base := evaluate(test, func(s sample) bool { return s.features[fCount] > bestT })
	fmt.Printf("\nbaseline (count > %.0f, tuned on train):\n", bestT)
	printMetrics("  ", base)
	fmt.Printf("  train F1 at this threshold: %.3f\n", bestF1)

	// Candidate: weighted z-score, standardized on train
	// NORMAL samples only.
	mean, std := normalStats(train)
	weights := [nFeatures]float64{1, 1, 1, 1, 1, 1, 1}
	score := func(s sample) float64 {
		total := 0.0
		for f := 0; f < nFeatures; f++ {
			z := (s.features[f] - mean[f]) / std[f]
			if z > 3 {
				z = 3
			}
			if z < -3 {
				z = -3
			}
			total += weights[f] * anomalyDir[f] * z
		}
		return total
	}
	candT, candTrainF1 := tuneThreshold(train, score)
	cand := evaluate(test, func(s sample) bool { return score(s) > candT })
	fmt.Printf("\ncandidate (z-score > %.3f, tuned on train):\n", candT)
	printMetrics("  ", cand)
	fmt.Printf("  train F1 at this threshold: %.3f\n", candTrainF1)
	fmt.Printf("\nfeature reference (train normal):\n")
	for f := 0; f < nFeatures; f++ {
		fmt.Printf("  %-15s mean=%8.3f std=%8.3f dir=%+.0f\n", featureNames[f], mean[f], std[f], anomalyDir[f])
	}
	fmt.Printf("\nverdict: ")
	switch {
	case cand.f1-base.f1 >= 0.10 && cand.precision >= 0.70:
		fmt.Printf("CANDIDATE_WINS (F1 +%.3f, precision %.3f)\n", cand.f1-base.f1, cand.precision)
	case base.f1 > cand.f1:
		fmt.Printf("BASELINE_WINS (F1 %.3f vs %.3f)\n", base.f1, cand.f1)
	default:
		fmt.Printf("NO_CLEAR_WIN (baseline F1 %.3f, candidate F1 %.3f)\n", base.f1, cand.f1)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "ml-eval:", err)
	os.Exit(1)
}

func loadLabels(path string) ([]interval, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []interval
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, ",")
		if len(parts) != 3 {
			return nil, fmt.Errorf("bad labels line: %q", line)
		}
		start, err1 := strconv.ParseInt(strings.TrimSpace(parts[0]), 10, 64)
		end, err2 := strconv.ParseInt(strings.TrimSpace(parts[1]), 10, 64)
		attack, err3 := strconv.Atoi(strings.TrimSpace(parts[2]))
		if err1 != nil || err2 != nil || err3 != nil || end <= start {
			return nil, fmt.Errorf("bad labels line: %q", line)
		}
		out = append(out, interval{time.Unix(start, 0), time.Unix(end, 0), attack == 1})
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no labels in %s", path)
	}
	return out, nil
}

func loadLog(path string) ([]logEntry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []logEntry
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1024*1024), 1024*1024)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		var e logEntry
		if err := json.Unmarshal([]byte(line), &e); err != nil {
			continue // non-JSON lines (e.g. rotation markers) are skipped
		}
		if e.IP == "" || e.Timestamp.IsZero() {
			continue
		}
		out = append(out, e)
	}
	return out, sc.Err()
}

// labelOf returns the label for a window start, or false
// when the window falls outside every labeled interval
// (the second return reports coverage).
func labelOf(intervals []interval, windowStart time.Time) (bool, bool) {
	windowEnd := windowStart.Add(10 * time.Second)
	for _, iv := range intervals {
		if windowStart.Before(iv.end) && windowEnd.After(iv.start) {
			return iv.attack, true
		}
	}
	return false, false
}

func aggregate(entries []logEntry, intervals []interval) []sample {
	type key struct {
		window int64
		ip     string
	}
	type agg struct {
		paths, uas, fps map[string]bool
		riskSum         int
		count           int
		challenges      int
		fpCounts        map[string]int
	}
	byKey := map[key]*agg{}
	// Window-global totals for the fingerprint-share
	// feature: per window, total entries + per-fingerprint
	// counts across all IPs.
	windowTotal := map[int64]int{}
	windowFP := map[int64]map[string]int{}
	for _, e := range entries {
		w := (e.Timestamp.Unix() / 10) * 10
		if _, covered := labelOf(intervals, time.Unix(w, 0)); !covered {
			continue
		}
		k := key{w, e.IP}
		a := byKey[k]
		if a == nil {
			a = &agg{paths: map[string]bool{}, uas: map[string]bool{}, fps: map[string]bool{}, fpCounts: map[string]int{}}
			byKey[k] = a
		}
		fp := e.Fingerprint
		if fp == "" {
			fp = "ja4:" + e.JA4
		}
		if fp == "ja4:" {
			fp = "none"
		}
		a.count++
		a.paths[e.Path] = true
		a.uas[e.UserAgent] = true
		a.fps[fp] = true
		a.fpCounts[fp]++
		a.riskSum += e.RiskScore
		if e.Event == "challenge" || e.Event == "block" {
			a.challenges++
		}
		windowTotal[w]++
		if windowFP[w] == nil {
			windowFP[w] = map[string]int{}
		}
		windowFP[w][fp]++
	}
	var samples []sample
	for k, a := range byKey {
		label, _ := labelOf(intervals, time.Unix(k.window, 0))
		// Fingerprint share: the sample IP's dominant
		// fingerprint's share of ALL entries in the window.
		// High when many IPs share one client stack (a
		// distributed flood from one tool), low when every
		// IP brings its own stack.
		topFP, topCount := "", 0
		for fp, n := range a.fpCounts {
			if n > topCount {
				topFP, topCount = fp, n
			}
		}
		fpShare := 0.0
		if windowTotal[k.window] > 0 {
			fpShare = float64(windowFP[k.window][topFP]) / float64(windowTotal[k.window])
		}
		s := sample{window: k.window, ip: k.ip, label: label}
		s.features[fCount] = float64(a.count)
		s.features[fDistinctPaths] = float64(len(a.paths))
		s.features[fDistinctUAs] = float64(len(a.uas))
		s.features[fDistinctFPs] = float64(len(a.fps))
		s.features[fMeanRisk] = float64(a.riskSum) / float64(a.count)
		s.features[fChallengeShare] = float64(a.challenges) / float64(a.count)
		s.features[fFPShare] = fpShare
		samples = append(samples, s)
	}
	return samples
}

func countLabel(samples []sample, label bool) int {
	n := 0
	for _, s := range samples {
		if s.label == label {
			n++
		}
	}
	return n
}

// normalStats returns per-feature mean/std over the NORMAL
// train samples. Std is floored so a constant feature
// cannot divide by zero (it then contributes ~0).
func normalStats(train []sample) (mean, std [nFeatures]float64) {
	var n float64
	for _, s := range train {
		if s.label {
			continue
		}
		n++
		for f := 0; f < nFeatures; f++ {
			mean[f] += s.features[f]
		}
	}
	if n == 0 {
		return mean, [nFeatures]float64{1, 1, 1, 1, 1, 1, 1}
	}
	for f := 0; f < nFeatures; f++ {
		mean[f] /= n
	}
	for _, s := range train {
		if s.label {
			continue
		}
		for f := 0; f < nFeatures; f++ {
			d := s.features[f] - mean[f]
			std[f] += d * d
		}
	}
	for f := 0; f < nFeatures; f++ {
		std[f] = math.Sqrt(std[f] / n)
		if std[f] < 1e-6 {
			std[f] = 1
		}
	}
	return mean, std
}

type metrics struct {
	tp, fp, tn, fn int
	precision      float64
	recall         float64
	f1             float64
}

func evaluate(samples []sample, flag func(sample) bool) metrics {
	var m metrics
	for _, s := range samples {
		switch {
		case flag(s) && s.label:
			m.tp++
		case flag(s) && !s.label:
			m.fp++
		case !flag(s) && !s.label:
			m.tn++
		default:
			m.fn++
		}
	}
	if m.tp+m.fp > 0 {
		m.precision = float64(m.tp) / float64(m.tp+m.fp)
	}
	if m.tp+m.fn > 0 {
		m.recall = float64(m.tp) / float64(m.tp+m.fn)
	}
	if m.precision+m.recall > 0 {
		m.f1 = 2 * m.precision * m.recall / (m.precision + m.recall)
	}
	return m
}

func printMetrics(prefix string, m metrics) {
	fmt.Printf("%sTP=%d FP=%d TN=%d FN=%d precision=%.3f recall=%.3f F1=%.3f\n",
		prefix, m.tp, m.fp, m.tn, m.fn, m.precision, m.recall, m.f1)
}

// tuneThreshold picks the threshold maximizing F1 on the
// given samples, scanning every distinct score value.
// Ties prefer the higher threshold (fewer false alarms).
func tuneThreshold(samples []sample, score func(sample) float64) (float64, float64) {
	seen := map[float64]bool{}
	var values []float64
	for _, s := range samples {
		v := score(s)
		if !seen[v] {
			seen[v] = true
			values = append(values, v)
		}
	}
	sort.Float64s(values)
	bestT, bestF1 := math.Inf(1), -1.0
	// Also consider "flag nothing" (threshold above max).
	candidates := append(values, math.Inf(1))
	for _, t := range candidates {
		m := evaluate(samples, func(s sample) bool { return score(s) > t })
		if m.f1 > bestF1 || (m.f1 == bestF1 && t > bestT) {
			bestT, bestF1 = t, m.f1
		}
	}
	return bestT, bestF1
}
